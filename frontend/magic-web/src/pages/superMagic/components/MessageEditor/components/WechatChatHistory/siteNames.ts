export function getKnownSiteName(host: string): string | undefined {
	const normalizedHost = host.toLowerCase().replace(/^www\./, "")
	const directName = SITE_NAMES[normalizedHost]
	if (directName) return directName

	const hostParts = normalizedHost.split(".")
	for (let index = 1; index < hostParts.length - 1; index++) {
		const name = SITE_NAMES[hostParts.slice(index).join(".")]
		if (name) return name
	}
	return undefined
}
