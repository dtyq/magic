import { describe, expect, it, vi } from "vitest"
import pubsub, { PubSubEvents } from "@/utils/pubsub"
import {
	isCurrentMicroAppLink,
	normalizeMicroAppHref,
	openMicroAppTab,
	parseMicroAppLink,
} from "../openMicroAppTab"

vi.mock("@/utils/pubsub", () => ({
	default: {
		publish: vi.fn(),
	},
	PubSubEvents: {
		Switch_Detail_Mode: "super_magic_switch_detail_mode",
		Open_Micro_App_Tab: "super_magic_open_micro_app_tab",
	},
}))

describe("openMicroAppTab", () => {
	it("parses micro-app links generated by the mention protocol", () => {
		expect(parseMicroAppLink("micro-app://957589322901028865")).toBe("957589322901028865")
		expect(parseMicroAppLink("micro-app://app%20one")).toBe("app one")
	})

	it("keeps parsing legacy micro_app:// links stored in historical messages", () => {
		expect(parseMicroAppLink("micro_app://957589322901028865")).toBe("957589322901028865")
		expect(parseMicroAppLink("micro_app://app%20one")).toBe("app one")
		expect(parseMicroAppLink("micro_app://app-1/path")).toBeNull()
		expect(normalizeMicroAppHref("micro_app://app-1")).toBe("app-1")
	})

	it("rejects malformed or unrelated links", () => {
		expect(parseMicroAppLink("https://example.com/micro-app://app-1")).toBeNull()
		expect(parseMicroAppLink("micro-app://app-1/path")).toBeNull()
		expect(parseMicroAppLink("micro-app://app-1/")).toBeNull()
		expect(parseMicroAppLink("micro-app://app-1?source=message")).toBeNull()
		expect(parseMicroAppLink("micro-app://app%2F1")).toBeNull()
		expect(parseMicroAppLink("micro-app://%E0%A4%A")).toBeNull()
		expect(parseMicroAppLink(undefined)).toBeNull()
	})

	it("normalizes hrefs and detects the app represented by the current route", () => {
		expect(normalizeMicroAppHref("micro-app://app-1")).toBe("app-1")
		expect(normalizeMicroAppHref("https://example.com")).toBe("https://example.com")
		expect(isCurrentMicroAppLink("app-1", "/super/micro-app/app-1")).toBe(true)
		expect(isCurrentMicroAppLink("app-1", "/micro_app/app-2")).toBe(false)
	})

	it("switches to files view and opens a micro-app tab", () => {
		expect(openMicroAppTab({ appId: "app-1", appName: "内购" })).toBe("app-1")
		expect(pubsub.publish).toHaveBeenCalledWith(PubSubEvents.Switch_Detail_Mode, "files")
		expect(pubsub.publish).toHaveBeenCalledWith(PubSubEvents.Open_Micro_App_Tab, {
			appId: "app-1",
			appName: "内购",
		})
	})

	it("ignores empty app ids", () => {
		vi.mocked(pubsub.publish).mockClear()
		expect(openMicroAppTab({ appId: "  " })).toBeNull()
		expect(pubsub.publish).not.toHaveBeenCalled()
	})
})
